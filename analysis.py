import numpy as np
import pandas as pd

def compute_asia_selection(df: pd.DataFrame, year: int = 2007) -> pd.DataFrame:
  """
  Selects Asia for the configured year, adds population in millions,
  computes descending life-expectancy rank, and sorts by rank then country.
  Default expected rows: 33.
  """
  # Filter for continent and year
  mask = (df["continent"].str.lower() == "asia") & (df["year"] == year)
  subset = df[mask].copy()

  # If no records found
  if subset.empty:
    raise ValueError(f"No records found for continent 'Asia' in year {year}.")

  # Add population in millions (pop is total population)
  subset["pop_millions"] = subset["pop"] / 1000000

  # Compute descending life-expectancy rank (highest lifeExp gets rank 1)
  subset["lifeExp_rank"] = (subset["lifeExp"].rank(ascending=False, method="min").astype(int))

  # Sort by rank, then country
  subset = subset.sort_values(by=["lifeExp_rank", "country"], ascending=[True, True]).reset_index(drop=True)

  # Return function
  return subset

def compute_philippines_summary(df: pd.DataFrame) -> pd.DataFrame:
  """
  Extracts all 12 Philippine observations, sorted by year, adding population
  in millions and life-expectancy change from the first observed year (1952).
  """
  ph_df = df[df["country"].str.lower() == "philippines"].copy()

  if ph_df.empty:
    raise ValueError("No records found for 'Philippines'.")

  ph_df = ph_df.sort_values(by="year").reset_index(drop=True)

  # Add population in millions
  ph_df["pop_millions"] = ph_df["pop"] / 1000000

  # Compute life-expectancy change relative to the first observed year
  baseline_life_exp = ph_df.iloc[0]["lifeExp"]
  ph_df["lifeExp_change"] = ph_df["lifeExp"] - baseline_life_exp

  # Return function
  return ph_df

def compute_numpy_population_matrix(df: pd.DataFrame):
  """
  Builds a 3x6 NumPy population matrix for the Philippines, Indonesia, and Thailand across years: 1982, 1987, 1992, 1997, 2002, 2007.
  Broadcasts the 1982 baseline (1982 = 100) to index every population.
  Returns a dictionary with raw matrix, broadcasted index matrix, shapes, boolean selection results, and loop verification checks.
  """
  countries = ["Philippines", "Indonesia", "Thailand"]
  years = [1982, 1987, 1992, 1997, 2002, 2007]

  # Filter data for selected countries and years
  filtered = df[df["country"].isin(countries) & df["year"].isin(years)]

  # Pivot into a matrix: rows = countries, columns = years
  pivot_df = filtered.pivot(index="country", columns="year", values="pop").reindex(index=countries, columns=years)
  if pivot_df.isnull().any().any():
    raise ValueError("Missing values detected in NumPy matrix subset.")
  raw_matrix = pivot_df.to_numpy(dtype=float)
  shape_before = raw_matrix.shape  # Should be (3, 6)

  # Broadcasting: Express every population as an index where 1982 = 100
  # Extract 1982 column column vector of shape (3, 1)
  baseline_1982 = raw_matrix[:, 0:1]
  broadcasted_matrix = (raw_matrix / baseline_1982) * 100
  shape_after = broadcasted_matrix.shape

  # Independent loop verification check
  loop_verified_matrix = np.empty_like(raw_matrix)
  for i in range(raw_matrix.shape[0]):
    base = raw_matrix[i, 0]
    for j in range(raw_matrix.shape[1]):
      loop_verified_matrix[i, j] = (raw_matrix[i, j] / base) * 100

  assert np.allclose(broadcasted_matrix, loop_verified_matrix), "Broadcast mismatch against independent loop calculation!"

  # Demonstrate Boolean selection and aggregation
  # e.g., Find countries where population in 2007 exceeded 70 million
  col_2007_idx = years.index(2007)
  bool_mask = raw_matrix[:, col_2007_idx] > 70000000
  filtered_countries = np.array(countries)[bool_mask]
  mean_pop_large_countries = np.mean(raw_matrix[bool_mask, col_2007_idx])

  # Return function
  return {
      "countries": countries,
      "years": years,
      "raw_matrix": raw_matrix,
      "broadcasted_matrix": broadcasted_matrix,
      "shape_before": shape_before,
      "shape_after": shape_after,
      "filtered_countries_2007": filtered_countries.tolist(),
      "mean_pop_large_countries_2007": mean_pop_large_countries,
  }

def compute_independent_asian_total(df: pd.DataFrame, year: int = 2007) -> int:
  """
  Computes the selected-year Asian population total independently of Pandas using pure NumPy arrays.
  Expected 2007 Asian population total: 3,811,953,827.
  """
  mask = (df["continent"] == "Asia") & (df["year"] == year)
  populations = df.loc[mask, "pop"].to_numpy(dtype=np.int64)

  # Return function
  return int(np.sum(populations))